def test_exact_current_outputs_never_change_readonly_prior_directory_lowering():
    current = {"generated/a/new.h", "objects/unit.o"}
    prior = {"generated/a/old.h", "bin/lunar-freeze-module"}
    assert expand_custody_reference("@work/objects/unit.o", current=current, prior=prior) == "/out/objects/unit.o"
    assert expand_custody_reference("@work/bin/lunar-freeze-module", current=current, prior=prior) == "/work/bin/lunar-freeze-module"
    # Sharing a parent does not expose the new header through the prior view.
    assert expand_custody_reference("@work-dir/generated/a", current=current, prior=prior) == "/work/generated/a"
    assert expand_custody_reference("@toolchain-dir/lib", current=current, prior=prior) == "/toolchain/lib"
    with pytest.raises(BuildExecutionError, match="custody_work_reference"):
        expand_custody_reference("@work/missing.o", current=current, prior=prior)
    with pytest.raises(BuildExecutionError, match="custody_directory_reference"):
        expand_custody_reference("@work-dir/objects", current=current, prior=prior)


def test_image_contains_complete_pinned_copies_and_prior_not_current(tmp_path):
    source, tools, work = (tmp_path / name for name in ("source", "toolchain", "work"))
    for root in (source, tools, work):
        root.mkdir()
    (source / "unit.c").write_bytes(b"original source")
    (tools / "resource").write_bytes(b"pinned resource")
    (work / "prior.h").write_bytes(b"actual earlier generated bytes")
    (work / "future.h").write_bytes(b"not yet observed")
    inputs = {"source": [record("unit.c", b"original source")],
              "toolchain": [record("resource", b"pinned resource")]}
    path = tmp_path / "image.tar"
    pin = _image_archive(path, inputs, {"source": source, "toolchain": tools},
                         [record("prior.h", b"actual earlier generated bytes")], work, lambda: None)
    (source / "unit.c").write_bytes(b"changed original after protection")
    (work / "prior.h").write_bytes(b"changed host readback after protection")
    with tarfile.open(path) as image:
        assert image.extractfile("source/unit.c").read() == b"original source"
        assert image.extractfile("toolchain/resource").read() == b"pinned resource"
        assert image.extractfile("work/prior.h").read() == b"actual earlier generated bytes"
        assert "work/future.h" not in image.getnames()
        assert image.getmember("source/unit.c").mode == 0o444
        assert image.getmember("out").isdir()
        assert not any(name.startswith("out/") for name in image.getnames())
    assert pin["sha256"] == sha(path.read_bytes())


