def comparison_vector(monkeypatch):
    base = base_recipe(sha(b"prep"), [record("unit.c")],
                       [record("lib/crt.o"), record("zig", executable=True)])
    generated = instrument(monkeypatch, base)
    wire, manifest = json.loads(generated.recipe_bytes), json.loads(generated.manifest_bytes)
    artifacts, compiler, linker = {}, {}, {}
    for row in manifest["compilations"]:
        raw = ("/out/" + row["target"].removeprefix("@work/") + ": /source/unit.c\n").encode()
        compiler[row["depfile"]] = artifacts[row["depfile"]] = raw
    for row in manifest["links"]:
        deps = ["/work/" + path.removeprefix("@work/") for path in row["explicit_inputs"]]
        raw = ("/out/" + row["target"].removeprefix("@work/") + ": " + " ".join(deps)
               + " /toolchain/lib/crt.o\n").encode()
        linker[row["depfile"]] = artifacts[row["depfile"]] = raw
    outputs = [record(out["path"], artifacts.get(out["path"], b"output"), out["executable"])
               for stage in wire["stages"] for command in stage["commands"] for out in command["outputs"]]
    common = {"expected_recipe_sha256": generated.sha256, "source_root": "/source",
              "toolchain_root": "/toolchain", "work_root": "/work", "current_output_root": "/out"}
    return generated, outputs, compiler, linker, common


def compare_vector(vector, *, compiler):
    generated, outputs, compilations, links, common = vector
    inventory = canonical(sorted(outputs, key=lambda row: row["path"]))
    common = {**common, "output_inventory_bytes": inventory, "expected_output_inventory_sha256": sha(inventory)}
    if compiler:
        return compare_compiler_dependencies(generated.recipe_bytes, dependency_artifacts=compilations, **common)
    return compare_linker_dependencies(generated.recipe_bytes, dependency_artifacts=links,
                                       manifest_bytes=generated.manifest_bytes,
                                       expected_manifest_sha256=sha(generated.manifest_bytes), **common)


def mutate_artifact(vector, *, compiler, change):
    _, outputs, compilations, links, _ = vector
    artifacts = compilations if compiler else links
    path = next(iter(artifacts))
    artifacts[path] = change(artifacts[path])
    for output in outputs:
        if output["path"] == path:
            output.update(size=len(artifacts[path]), sha256=sha(artifacts[path]))


@pytest.mark.parametrize("compiler", [True, False])
def test_original_comparators_separate_current_targets_from_readonly_prior_inputs(monkeypatch, compiler):
    vector = comparison_vector(monkeypatch)
    assert compare_vector(vector, compiler=compiler).canonical_bytes
    mutate_artifact(vector, compiler=compiler, change=lambda raw: raw.replace(b"/out/", b"/work/", 1))
    with pytest.raises((CompilerDependencyError, LinkDependencyError), match="target"):
        compare_vector(vector, compiler=compiler)


