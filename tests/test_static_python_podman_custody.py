@pytest.mark.parametrize("change", [
    "writable-root", "capability", "privilege", "argv", "ambient-env", "borrowed-namespace",
    "weaken-seccomp", "memory", "pids", "cpu", "fsize", "core", "current-readonly",
    "unknown-mount", "resolver-source", "writable-resolver", "writable-shm", "duplicate-mount",
    "resolver-add-rw", "resolver-add-exec", "shm-duplicate-size",
])
def test_actual_oci_policy_refuses_drift_before_start(tmp_path, monkeypatch, change):
    vector = runtime_vector(tmp_path, monkeypatch)
    spec = vector[-1]
    process, linux = spec["process"], spec["linux"]
    if change == "writable-root":
        spec["root"]["readonly"] = False
    elif change == "capability":
        process["capabilities"]["effective"] = ["CAP_SYS_ADMIN"]
    elif change == "privilege":
        process["noNewPrivileges"] = False
    elif change == "argv":
        process["args"] = ["/unexpected/program"]
    elif change == "ambient-env":
        process["env"].append("UNKNOWN=host-value")
    elif change == "borrowed-namespace":
        linux["namespaces"][0]["path"] = "/proc/1/ns/pid"
    elif change == "weaken-seccomp":
        linux["seccomp"]["syscalls"] = []
    elif change == "memory":
        linux["resources"]["memory"]["limit"] *= 2
    elif change == "pids":
        linux["resources"]["pids"]["limit"] += 1
    elif change == "cpu":
        linux["resources"]["cpu"]["quota"] += 1
    elif change in {"fsize", "core"}:
        index = 1 if change == "fsize" else 0
        process["rlimits"][index]["hard"] += 1
    elif change == "current-readonly":
        spec["mounts"][0]["options"].remove("rw")
    elif change == "unknown-mount":
        spec["mounts"].append({"destination": "/unknown", "source": "/host", "type": "bind"})
    elif change == "resolver-source":
        spec["mounts"][-1]["source"] = "/ambient/resolv.conf"
    elif change == "writable-resolver":
        spec["mounts"][-1]["options"].remove("ro")
    elif change == "writable-shm":
        spec["mounts"][2]["options"].remove("ro")
    elif change == "duplicate-mount":
        spec["mounts"].append(spec["mounts"][0])
    elif change == "resolver-add-rw":
        spec["mounts"][-1]["options"].append("rw")
    elif change == "resolver-add-exec":
        spec["mounts"][-1]["options"].append("exec")
    elif change == "shm-duplicate-size":
        spec["mounts"][2]["options"].append("size=999999999")
    with pytest.raises(BuildExecutionError, match="custody_runtime_"):
        runtime_check(vector)


